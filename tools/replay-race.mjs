import { readFile } from 'node:fs/promises';
import { parseTelemetryCsv } from '../public/shared/race-telemetry.js';
import { LapAnalyzer } from '../public/shared/lap-analysis.js';
import { cleanLap } from '../server/memory.js';
import { chooseFocus } from '../server/coaching-loop.js';
const file=process.argv[2]||'fixtures/race-session.csv';
const samples=parseTelemetryCsv(await readFile(file,'utf8'));
const laps=[];
const analyzer=new LapAnalyzer({onLap:function(lap){laps.push(cleanLap(lap));console.log(lap.summary);}});
for(const sample of samples) analyzer.push(sample);
const focus=chooseFocus(laps.toReversed());
console.log(JSON.stringify({input:file,samples:samples.length,validLaps:laps.length,measuredFocus:focus?{corner:focus.corner,actionSeconds:focus.actionSeconds,actionMeters:focus.actionMeters,direction:focus.actionDirection,evidence:focus.evidenceLapIds.length}:null},null,2));
